/**
 * Cloudflare Logs (дашборд) в наблюдаемом поведении обрезает второй
 * аргумент console.error(text, errorObject) до одного только стека,
 * без err.message — из-за этого несколько раз реальная причина сбоя
 * (напр. код HTTP-ответа апстрима) была не видна в логах вообще, только
 * стектрейс без единого слова о том, что именно пошло не так. Поэтому
 * везде в проекте текст ошибки нужно явно вклеивать В САМУ строку лога,
 * а не полагаться на то, как консоль сериализует объект.
 */
export function errorReason(err: unknown): string {
  return err instanceof Error ? err.message : String(err);
}
