/**
 * Общая пауза между последовательными запросами к апстримам (Jolpica/
 * OpenF1). Раньше пауза была захардкожена локально внутри
 * cron/syncRoundResults.ts и не применялась на границах между фазами/
 * функциями — из-за чего последний запрос одной фазы мог улететь сразу
 * вслед за первым запросом следующей без единой паузы между ними, и
 * burst-лимит Jolpica (4/сек = 250мс/запрос) всё равно пробивался. Теперь
 * это общий хелпер: любое место, которое делает больше одного
 * последовательного вызова к апстриму, должно ставить sleep() между
 * ними — не только "внутри одной функции", а вообще везде на пути cron.
 */
export const UPSTREAM_PACE_MS = 350;

export function sleep(ms: number = UPSTREAM_PACE_MS): Promise<void> {
  return new Promise((resolve) => setTimeout(resolve, ms));
}
